/**
 * @brief 自定义printf函数
 *
 * @note 此函数为保险用，为了确保输出的原子性，会使用阻塞方式等待UART1完成发送。
 *       一般输出建议使用logPrintln函数。
 *
 * @note 缓冲区改为 static（原先是 1024B 的栈上局部数组）：本函数只在启动阶段、
 *       Error_Handler/assert/栈溢出/malloc 失败等错误路径调用，一旦从任务上下文
 *       触发（如 vApplicationMallocFailedHook 可能在任何小栈任务里执行），
 *       1024B 的栈帧会把 512B 栈的任务直接压爆，导致错误信息打印不出来、
 *       甚至破坏 FreeRTOS 堆。改为静态缓冲区后这些路径不再需要 1KB 栈空间。
 *       以上路径都是"单线程/致命错误"场景，共用同一缓冲区不会产生并发问题
 *       （正常业务日志请走 logPrintln，不要调用本函数）。
 *
 * @param fmt 格式字符串
 * @param ... 可变参数
 */
void my_printf(const char *fmt, ...) {
    static char buffer[1024];
    va_list ap;
    int len, actual_len;

    va_start(ap, fmt);
    len = vsnprintf(buffer, 1023, fmt, ap);
    va_end(ap);

    actual_len = (len > 1023) ? (1023) : len;

    HAL_UART_AbortTransmit(&huart1);
    HAL_UART_Transmit(&huart1, (uint8_t *)(buffer), actual_len, 0xFFFF);
}

/**
 * @brief 自定义print函数
 *
 * @note 此函数同样为保险用，使用完全阻塞方式发送。
 *
 * @param str 字符串指针
 * @param len 字符串长度
 */
void my_print(const char *str, uint32_t len) {
    const uint16_t chunk_size = 0xFFFF;
    uint32_t offset = 0;

    while (offset < len) {
        uint16_t send_len = (len - offset > chunk_size) ? chunk_size : (uint16_t)(len - offset);
        HAL_UART_Transmit(&huart1, (uint8_t *)(str + offset), send_len, 0xFFFFFF);
        // 等待发送完成，确保完全阻塞
        while (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_TC) == RESET)
            ;
        offset += send_len;
    }
}

